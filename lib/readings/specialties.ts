/** 拼成常驻块（约 700 字） */
export function quickRefBlock(): string {
  const lines = QUICK_REF.map((s) => `- ${s.name}：${s.use}。**忌**：${s.ban}。`).join('\n');
  return `\n\n# 专项速查（按问句自行归类，可同时适用多个专项；细则见规范对应章）
${lines}
若本问不属于以上任何专项，按通用规则判断，不要硬套某一节。`;
}
