/** 拼成注入块（未命中专项时返回空串） */
export function specialtyBlock(spec: Specialty): string {
  const s = SPECIALTIES[spec];
  return s ? `\n\n# 本问专项要点（${s.label}，规范 ${s.chapter}）\n${s.brief}` : '';
}
